package com.temporal.gremlin.translator;

import com.temporal.gremlin.query.TemporalQuerySpec;
import com.temporal.gremlin.query.TemporalTransaction;
import org.apache.tinkerpop.gremlin.process.traversal.dsl.graph.GraphTraversalSource;
import org.apache.tinkerpop.gremlin.structure.Graph;
import org.apache.tinkerpop.gremlin.tinkergraph.structure.TinkerGraph;

/**
 * Transforms temporal Gremlin query strings into standard Gremlin bytecode.
 * Supports both queries (TemporalQuerySpec) and mutations
 * (TemporalTransaction).
 * 
 * This class provides both a function-based API and a command-line interface
 * for transforming temporal queries and mutations.
 */
public class TemporalQueryStringTransformer {

    private final TemporalQueryParser parser;
    private final TemporalGremlinTranslator translator;
    private final GraphTraversalSource g;
    private final Graph graph;

    /**
     * Creates a new transformer with a provided GraphTraversalSource
     */
    public TemporalQueryStringTransformer(GraphTraversalSource g) {
        this.parser = new TemporalQueryParser();
        this.translator = new TemporalGremlinTranslator(g);
        this.g = g;
        this.graph = null;
    }

    /**
     * Creates a new transformer with its own TinkerGraph instance
     */
    public TemporalQueryStringTransformer() {
        this.graph = TinkerGraph.open();
        this.g = graph.traversal();
        this.parser = new TemporalQueryParser();
        this.translator = new TemporalGremlinTranslator(g);
    }

    /**
     * Transforms a temporal query or mutation string into standard Gremlin
     * bytecode.
     * Automatically detects whether the input is a query or mutation.
     * 
     * @param temporalQuery The temporal Gremlin query or mutation string
     * @return TranslationResult containing the bytecode and metrics
     * @throws IllegalArgumentException if the query string is invalid
     */
    public TemporalGremlinTranslator.TranslationResult transform(String temporalQuery) {
        Object parsed = parser.parseQuery(temporalQuery);

        // Translate based on type
        if (parsed instanceof TemporalQuerySpec) {
            return translator.translate((TemporalQuerySpec) parsed);
        } else if (parsed instanceof TemporalTransaction) {
            return translator.translate((TemporalTransaction) parsed);
        } else {
            throw new IllegalArgumentException("Unknown parsed type: " + parsed.getClass());
        }
    }

    /**
     * Set the verbosity of the translation process.
     * When true, additional metadata comments are added to the generated bytecode.
     */
    public void setVerbose(boolean verbose) {
        translator.setVerbose(verbose);
    }

    /**
     * Transforms a temporal query string and returns the bytecode as a string.
     * 
     * @param temporalQuery The temporal Gremlin query string
     * @return The generated Gremlin bytecode as a string
     */
    public String transformToString(String temporalQuery) {
        TemporalGremlinTranslator.TranslationResult result = transform(temporalQuery);
        return result.bytecode.toString();
    }

    /**
     * Closes the internal graph if one was created
     */
    public void close() {
        if (graph != null) {
            try {
                g.close();
                graph.close();
            } catch (Exception e) {
            }
        }
    }

    /**
     * Main method for command-line usage.
     * 
     * Usage: java TemporalQueryStringTransformer
     * "g.V().hasLabel('Conference').temporalBefore('Meeting')"
     */
    public static void main(String[] args) {
        if (args.length == 0) {
            printUsage();
            System.exit(1);
        }

        String queryString = args[0];
        boolean quiet = args.length > 1 && (args[1].equals("-q") || args[1].equals("--quiet"));

        TemporalQueryStringTransformer transformer = null;
        try {
            transformer = new TemporalQueryStringTransformer();

            if (!quiet) {
                System.out.println("╔════════════════════════════════════════════════════════╗");
                System.out.println("║     Temporal Query String Transformer                 ║");
                System.out.println("╚════════════════════════════════════════════════════════╝\n");

                System.out.println("Input Temporal Query:");
                System.out.println("  " + queryString);
                System.out.println();
            }

            transformer.setVerbose(!quiet);

            TemporalGremlinTranslator.TranslationResult result = transformer.transform(queryString);

            if (!quiet) {
                System.out.println("Translation Successful!");
                System.out.println("─────────────────────────────────────────────────────────");
                result.printReport();
                System.out.println();

                System.out.println("Generated Gremlin Steps:");
                for (int i = 0; i < result.optimizedSteps.size(); i++) {
                    System.out.println("  " + (i + 1) + ". " + result.optimizedSteps.get(i));
                }
                System.out.println();

                System.out.println("Generated Bytecode:");
                System.out.println("  " + result.bytecode);
                System.out.println();

                System.out.println("Translation Metrics:");
                System.out.printf("  Total Time:       %.3f ms%n", result.metrics.getTotalTime());
                System.out.printf("  Parsing Time:     %.3f ms%n", result.metrics.getParsingTime());
                System.out.printf("  Transform Time:   %.3f ms%n", result.metrics.getTransformTime());
                System.out.printf("  Optimization Time: %.3f ms%n", result.metrics.getOptimizationTime());
                System.out.printf("  Codegen Time:     %.3f ms%n", result.metrics.getCodegenTime());
                System.out.printf("  Steps Generated:  %d%n", result.optimizedSteps.size());
                System.out.printf("  Bytecode Size:    %d bytes%n", result.metrics.getBytecodeSize());
                System.out.println();
            } else {
                // In quiet mode, just return the bytecode string
                System.out.println(result.bytecode);
            }
        } catch (IllegalArgumentException e) {
            System.err.println("Error: " + e.getMessage());
            if (!quiet) {
                System.err.println();
                printUsage();
            }
            System.exit(1);
        } catch (Exception e) {
            if (!quiet) {
                System.err.println("Unexpected error: " + e.getMessage());
                e.printStackTrace();
            }
            System.exit(1);
        } finally {
            if (transformer != null) {
                transformer.close();
            }
        }
    }

    private static void printUsage() {
        System.out.println("Usage: java TemporalQueryStringTransformer <temporal-query> [-q|--quiet]");
        System.out.println();
        System.out.println("Supported Query Formats:");
        System.out.println("  1. Label-based queries:");
        System.out.println("     g.V().hasLabel('Conference').temporalBefore('Meeting')");
        System.out.println("     g.V().hasLabel('Event').temporalOverlaps('Meeting')");
        System.out.println();
        System.out.println("  2. With lifetime constraints:");
        System.out.println("     g.V().hasLabel('Event').lifetime(1234567890, 1234567900).temporalOverlaps('Meeting')");
        System.out.println();
        System.out.println("  3. Reference vertex queries:");
        System.out.println("     g.V(123).temporalOverlaps('Meeting')");
        System.out.println("     g.V(123).temporalOverlaps()");
        System.out.println();
        System.out.println("  4. Add vertex with lifetime:");
        System.out.println("     g.addV('Person').property('name', 'John').lifetime(start, end)");
        System.out.println();
        System.out.println("  5. Add edge with lifetime:");
        System.out.println("     g.addE('knows').from(v1).to(v2).lifetime(start, end)");
        System.out.println();
        System.out.println("Supported Allen Operators:");
        System.out.println("  temporalBefore, temporalAfter, temporalOverlaps, temporalDuring, temporalStarts,");
        System.out.println("  temporalEnds, temporalMeets, temporalStartedBy, temporalEndedBy, temporalContains,");
        System.out.println("  temporalOverlappedBy, temporalMetBy, temporalEqual");
    }
}
