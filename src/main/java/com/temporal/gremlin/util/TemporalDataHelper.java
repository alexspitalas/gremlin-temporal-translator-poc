package com.temporal.gremlin.util;

import com.temporal.gremlin.query.TemporalTransaction;
import com.temporal.gremlin.translator.TemporalGremlinTranslator;
import com.temporal.gremlin.executor.GremlinExecutor;
import java.time.Instant;

/**
 * Utility class for common temporal data operations.
 * Provides standardized methods for adding temporal vertices and edges using the translator.
 * 
 * This ensures consistent usage of TemporalTransaction across demos and applications.
 */
public class TemporalDataHelper {
    
    private final TemporalGremlinTranslator translator;
    private final GremlinExecutor executor;
    
    /**
     * Creates a new TemporalDataHelper with the given translator and executor.
     * 
     * @param translator The translator to use for converting TemporalTransaction to bytecode
     * @param executor   The executor to use for running the generated bytecode
     */
    public TemporalDataHelper(TemporalGremlinTranslator translator, GremlinExecutor executor) {
        this.translator = translator;
        this.executor = executor;
    }
    
    /**
     * Add a vertex with label, single property, and lifetime.
     * 
     * @param label     Vertex label
     * @param propName  Property name
     * @param propValue Property value
     * @param start     Lifetime start
     * @param end       Lifetime end
     */
    public void addVertex(String label, String propName, Object propValue, Instant start, Instant end) {
        TemporalTransaction tx = new TemporalTransaction();
        tx.addVertex(label)
                .property(propName, propValue)
                .lifetime(start, end);
        
        TemporalGremlinTranslator.TranslationResult result = translator.translate(tx);
        executor.execute(result.bytecode);
    }
    
    /**
     * Add a vertex with label, two properties, and lifetime.
     * 
     * @param label      Vertex label
     * @param propName1  First property name
     * @param propValue1 First property value
     * @param propName2  Second property name
     * @param propValue2 Second property value
     * @param start      Lifetime start
     * @param end        Lifetime end
     */
    public void addVertex(String label, 
                          String propName1, Object propValue1,
                          String propName2, Object propValue2,
                          Instant start, Instant end) {
        TemporalTransaction tx = new TemporalTransaction();
        tx.addVertex(label)
                .property(propName1, propValue1)
                .property(propName2, propValue2)
                .lifetime(start, end);
        
        TemporalGremlinTranslator.TranslationResult result = translator.translate(tx);
        executor.execute(result.bytecode);
    }
    
    /**
     * Add an edge with label, property, and lifetime.
     * 
     * @param fromId    Source vertex ID
     * @param toId      Target vertex ID
     * @param label     Edge label
     * @param propName  Property name
     * @param propValue Property value
     * @param start     Lifetime start
     * @param end       Lifetime end
     */
    public void addEdge(Object fromId, Object toId, String label,
                        String propName, Object propValue,
                        Instant start, Instant end) {
        TemporalTransaction tx = new TemporalTransaction();
        tx.addEdge(label, fromId, toId)
                .property(propName, propValue)
                .lifetime(start, end);
        
        TemporalGremlinTranslator.TranslationResult result = translator.translate(tx);
        executor.execute(result.bytecode);
    }
}
